'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = { window: { location: { href: 'https://shop.test/index.php' } }, URL, Intl };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../../frontend/public/assets/js/chat-purchase.js'), 'utf8'), context);
const ui = context.window.SkinSyntaxPurchase;
const product = { id: '1', name: '<script>alert(1)</script>', brand: 'Test', price: 100000, detail_url: 'javascript:alert(1)' };
ui.render({ stage: 'choose', offer: 'offer-a', products: [product], quantity: 2 });
ui.render({ stage: 'selected', offer: 'offer-a', product, quantity: 2, subtotal: 200000 });
const restored = ui.render({ stage: 'choose', offer: 'offer-a', quantity: 2 });
assert.match(restored, /data-buy-select="1"/, 'Changing product restores original options');
assert.match(restored, /data-buy-quantity="2"/, 'Quantity remains available for reselection');
assert.ok(!restored.includes('<script>'), 'Catalog names are escaped');
assert.ok(!restored.includes('href="javascript:'), 'Executable product links are rejected');
const otherOffer = ui.render({ stage: 'choose', offer: 'offer-b', quantity: 1 });
assert.ok(!otherOffer.includes('data-buy-select="1"'), 'Options cannot leak across offers');
const cart = ui.render({ stage: 'cart', items: [], cart_url: '/index.php?r=giohang' });
assert.match(cart, /Giỏ hàng đang trống/, 'Empty cart still renders');
console.log('PASS: 6 chat purchase UI regressions');
